"""
内置技能集
==========
开箱即用的 4 个技能，演示 Skill（SOP + 工具绑定）与 Function Call 的协作方式：

1. MathCalculatorSkill  数学计算技能  → 绑定 calculator 函数工具
2. BusinessDataSkill    业务数据查询  → 绑定 data_query 函数工具
3. KnowledgeQASkill     知识库问答    → 走 RAG 检索，无专用函数工具
4. WebSearchSkill       联网信息检索  → 绑定 MCP web_search / get_current_time 函数工具

新增技能：继承 BaseSkill 声明类属性，然后加入本文件 get_default_skills() 即可被自动装配。
"""
from typing import List  # 类型注解：列表
from modules.skills.base_skill import BaseSkill  # 技能基类：所有内置技能都继承它


# 【什么】数学计算技能
# 【作用】遇到算数问题时引导 LLM 调 calculator 工具，避免心算给错数字
# 【为什么】LLM 心算大数/复杂运算极易出错；把数值计算交给确定性的计算器函数才能保证结果精确
class MathCalculatorSkill(BaseSkill):  # 数学计算技能
    """数学计算技能：把自然语言问题转成表达式，调用计算器函数完成精确计算。"""

    name = "math_calculator"  # 技能唯一标识（注册表字典键）
    display_name = "数学计算"  # 展示名：注入文本与 CLI 里显示
    description = "处理四则运算、幂运算、三角函数、开方、取模等各类数学计算问题，保证结果精确。"  # 职责说明：给匹配器与 LLM 看
    trigger_keywords = [  # 触发词列表：命中即计入 L1 得分
        "计算", "算一下", "算一算", "等于几", "等于多少", "结果是多少",  # 通用计算诉求短语
        "加", "减", "乘", "除", "乘以", "除以",  # 四则运算词（单字为弱证据）
        "平方", "开方", "次方", "根号",  # 幂与开方相关词
        "sin", "cos", "tan", "sqrt", "对数",  # 三角函数与常见函数名
        "数学", "百分数", "百分比", "求和",  # 数学领域词与统计诉求
    ]
    bound_tools = ["calculator"]   # 推荐工具：计算器，保证数值精确
    priority = 10                  # 同分优先级；数值越大越优先选中
    instructions = (  # SOP 作业流程：激活后注入给 LLM 的步骤指引
        "1. 从用户问题中识别已知数值与运算关系，转换为合法数学表达式（如 '2加3' → '2+3'）；\n"  # 第一步：语义转表达式
        "2. 必须调用 calculator 函数完成计算，禁止凭记忆心算给出数值结果；\n"  # 第二步：强制走工具，禁心算
        "3. 向用户展示「计算式 → 结果」，带单位的问题需注明单位；\n"  # 第三步：结果展示规范
        "4. 若表达式无法唯一确定（如缺少必要数值），先向用户追问澄清，不要猜测参数。"  # 第四步：信息不足时追问而非瞎猜
    )


# 【什么】企业业务数据查询技能
# 【作用】查用户/订单/库存时按 SOP 调 data_query，并禁止编造查不到的记录
# 【为什么】业务数据必须来自真实查询接口；SOP 约束「先查再答、查不到实说」，杜绝模型编造业务记录
class BusinessDataSkill(BaseSkill):  # 企业业务数据查询技能
    """企业业务数据查询技能：按 SOP 调用 data_query 函数查询用户/订单/库存。"""

    name = "business_data_query"  # 技能唯一标识
    display_name = "企业数据查询"  # 展示名
    description = "查询企业内部业务数据：用户信息、订单状态、库存数量与价格等。"  # 职责说明
    trigger_keywords = [  # 触发词列表
        "订单", "用户信息", "库存", "查一下", "查询",  # 核心业务对象与查询动词
        "客户", "销量", "销售额", "发货", "配送", "付款",  # 交易与履约相关词
        "单价", "价格", "还有多少", "存货", "业务数据",  # 价格与库存相关词
    ]
    bound_tools = ["data_query"]   # 推荐工具：业务数据查询
    priority = 10                  # 同分优先级，与数学计算同级
    instructions = (  # SOP 作业流程
        "1. 先明确查询的数据类型（users 用户 / orders 订单 / inventory 库存）与记录ID；\n"  # 第一步：定位数据类型与记录
        "2. 调用 data_query 函数获取数据，record_id 不明确时可先查该类型全部记录ID再精查；\n"  # 第二步：走工具查询，ID 不明先粗查再精查
        "3. 用表格或条目形式结构化展示结果，金额保留两位小数；\n"  # 第三步：结果展示规范
        "4. 查不到记录时如实告知，禁止编造业务数据；涉及敏感信息按脱敏结果展示。"  # 第四步：无结果实说、敏感信息脱敏
    )


# 【什么】知识库问答技能
# 【作用】要求 LLM 只依据 RAG 召回内容作答并标注来源，无依据时明确说未检索到
# 【为什么】制度/手册类问题必须「有据可依」；约束只引用召回内容并标注来源，防止模型用通用常识冒充企业规定
class KnowledgeQASkill(BaseSkill):  # 知识库问答技能
    """知识库问答技能：依据 RAG 召回内容回答，强调引用来源、无据不答。"""

    name = "knowledge_qa"  # 技能唯一标识
    display_name = "知识库问答"  # 展示名
    description = "基于企业知识库（制度文档、产品手册、FAQ）回答问题，答案附来源。"  # 职责说明
    trigger_keywords = [  # 触发词列表
        "根据公司", "公司规定", "制度", "手册", "文档里",  # 指向企业内部依据的短语
        "知识库", "政策", "流程是怎样", "规范", "FAQ",  # 知识库载体与政策类词
        "条款", "报销标准", "年假", "操作指南", "产品说明",  # 典型制度与产品文档主题
    ]
    bound_tools = []   # 无专用函数工具，答案走 RAG 检索召回
    priority = 5       # 优先级低于带专用工具的技能（值越小越靠后）
    instructions = (  # SOP 作业流程
        "1. 严格以【知识库参考】中召回的内容为事实依据回答，不得引入库外信息或编造；\n"  # 第一步：只用召回内容作答
        "2. 回答中标注信息来源文件名与相关度，多来源时分点列出；\n"  # 第二步：标注来源
        "3. 知识库无相关内容或内容明显不足时，明确告知「知识库未检索到相关规定」，\n"  # 第三步前半：无据时如实告知
        "   可建议用户补充关键词或转人工，不要用通用常识冒充制度结论；\n"  # 第三步后半：给补救路径，禁冒充结论
        "4. 涉及制度条款解读时，原文引用关键句后再给解释。"  # 第四步：先引原文再解读
    )


# 【什么】联网信息检索技能
# 【作用】时效性问题走 MCP 搜索/报时工具；工具不可用时要求如实说无法联网
# 【为什么】新闻/天气/时间这类时效信息模型自身知识必然过时；强制走实时工具并在不可用时坦白，杜绝编造实时信息
class WebSearchSkill(BaseSkill):  # 联网信息检索技能
    """联网信息检索技能：时效性问题调用 MCP 搜索函数；时间问题调用报时函数。"""

    name = "web_search"  # 技能唯一标识
    display_name = "联网信息检索"  # 展示名
    description = "获取互联网实时信息：新闻、天气、最新政策、近期事件，以及当前时间查询。"  # 职责说明
    trigger_keywords = [  # 触发词列表
        "最新", "新闻", "网上", "联网", "搜索一下", "帮我搜",  # 时效性与搜索诉求词
        "实时", "今天新闻", "现在几点", "当前时间", "天气预报",  # 实时信息与时间天气诉求
        "最近发生", "最新消息", "网上怎么说",  # 近期事件与舆情诉求
    ]
    bound_tools = ["web_search", "get_current_time"]   # MCP 工具：搜资讯 / 取当前时间
    priority = 8                                       # 同分优先级，低于带本地工具的技能
    instructions = (  # SOP 作业流程
        "1. 判断需求：事实/资讯类调用 web_search 函数，时间类调用 get_current_time 函数；\n"  # 第一步：按需求类型选工具
        "2. 搜索关键词使用 2~4 个核心词，必要时分多次搜索交叉验证；\n"  # 第二步：检索词规范与交叉验证
        "3. 回答基于搜索返回的内容，并附来源链接；信息之间有冲突时说明分歧；\n"  # 第三步：基于结果作答、附链接、冲突要说明
        "4. 搜索工具不可用（未配置 Key 或服务降级）时，明确告知无法联网，不要编造实时信息。"  # 第四步：工具不可用时坦白，禁编造
    )


# 【什么】内置技能清单的装配入口
# 【作用】返回 4 个技能实例供 SkillRegistry 注册；新增技能加进这个列表即可生效
# 【为什么】把「有哪些内置技能」收口成一个函数，装配方（注册器初始化）只需调它，新增技能改一处即生效
def get_default_skills() -> List[BaseSkill]:  # 返回内置技能实例列表
    """内置默认技能集（注意：返回的是实例，供 SkillRegistry 注册）。"""
    return [
        MathCalculatorSkill(),  # 数学计算技能实例
        BusinessDataSkill(),  # 企业数据查询技能实例
        KnowledgeQASkill(),  # 知识库问答技能实例
        WebSearchSkill(),  # 联网信息检索技能实例
    ]
